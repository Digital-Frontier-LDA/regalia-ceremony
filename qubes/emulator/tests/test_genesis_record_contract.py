#!/usr/bin/env python3
"""The format contract of offline-keys.record.json with regalia-kms (regalia-ceremony#134, regalia-htl).

regalia-kms's `manifest propose --genesis` takes K_A from this record and nowhere else (deploy/baremetal/manifest.py,
offline_keys_record, on kms main since #438, 6fe15615; the call at :652, the required flag at :635). This file pins what
kms reads, as kms reads it, so a change on this side fails HERE before a genesis does. Any change to these values is
announced to regalia-kms first (#134):
  * exactly the 14 top-level fields (kms OFFLINE_KEYS_FIELDS);
  * schema regalia.offline-keys-record/v1, event "generate";
  * signed by the root over b"regalia.offline-keys-record/v1\\0" + canonical(record) (kms OFFLINE_KEYS_DOMAIN; the
    retired b"regalia-ceremony-record/v1\\0" that #134's text still names is accepted nowhere since regalia-avz, #178);
  * publics["anchor-policy"] = {alg: ecdsa-p256, spki}, its point equal to anchor_policy_entry {alg, key: 04||X||Y};
  * operation_proof["anchor-policy"] == "verified".
offline-keys.py genesis_record is the ceremony's own copy of those rules (the genesis step runs it before any kms code).
With REGALIA_KMS_TREE set to a regalia-kms checkout, every case below is also judged by kms's own offline_keys_record,
and the two must agree; without it those cross-checks say SKIP and are not counted.
"""

def _load(name, path):
    loader = importlib.machinery.SourceFileLoader(name, path)
    module = importlib.util.module_from_spec(importlib.util.spec_from_loader(name, loader))
    loader.exec_module(module)
    return module


ok = _load("offline_keys", os.path.join(HERE, "..", "..", "scripts", "offline-keys.py"))
writer = _load("writer_tests", os.path.join(HERE, "test_card_record_writer.py"))
deps = _load("emulator_deps", os.path.join(HERE, "emulator_deps.py"))

# regalia-kms deploy/baremetal/manifest.py at 6fe15615 (#438), lines 222-229: copied by value, never imported
KMS_OFFLINE_KEYS_SCHEMA = "regalia.offline-keys-record/v1"
KMS_OFFLINE_KEYS_DOMAIN = b"regalia.offline-keys-record/v1\x00"
KMS_RETIRED_RECORD_DOMAIN = b"regalia-ceremony-record/v1\x00"
KMS_OFFLINE_KEYS_FIELDS = ("schema", "event", "threshold", "shares", "slip39_identifier", "master_id", "publics", "root_entry",
                           "anchor_policy_entry", "root_fingerprint", "files", "operation_proof", "tool", "at")


def _kms():
    """regalia-kms's manifest module from REGALIA_KMS_TREE, or None."""
    tree = os.environ.get("REGALIA_KMS_TREE")
    if not tree:
        return None
    sys.path.insert(0, tree)
    try:
        import deploy.baremetal.manifest as manifest      # noqa: PLC0415 - the consumer's own code, from its tree
    finally:
        sys.path.remove(tree)
    return manifest


KMS = _kms()


class Contract(unittest.TestCase):
    """One offline set generated by offline-keys.py (the writer tests' fixture), its generation record, and the root's
    private key to re-sign mutated records, so each content rule is judged with a valid signature."""

    def setUp(self):
        writer.Writer.setUp(self)
        with open(os.path.join(self.gen, "offline-keys.record.json")) as f:
            self.document = json.load(f)
        with open(self.sealed) as f:
            sealed = json.load(f)
        master = ok.combine(self.shares[:2], sealed)[0]     # noqa: the fixture's own shares
        self.root_key = ok._private_key(ok.unseal(master, sealed)["keys"]["root"])

    def signed(self, record, domain=KMS_OFFLINE_KEYS_DOMAIN, key=None):
        return {"record": record, "signature": (key or self.root_key).sign(domain + ok.canonical(record)).hex()}

    def verdict(self, document):
        """(ours, kms's): None when accepted, else the refusal's text; kms's is "SKIP" without REGALIA_KMS_TREE."""
        try:
            ok.genesis_record(copy.deepcopy(document), self.root)
            ours = None
        except ok.Refused as refused:
            ours = str(refused)
        if KMS is None:
            return ours, "SKIP"
        try:
            KMS.offline_keys_record(copy.deepcopy(document), KMS.root_key(self.root))     # as propose takes ROOT-KEY
            theirs = None
        except KMS.Refused as refused:
            theirs = str(refused)
        return ours, theirs

    def agree(self, document, accepted):
        ours, theirs = self.verdict(document)
        self.assertEqual(ours is None, accepted, "offline-keys.py: %s" % ours)
        if theirs != "SKIP":
            self.assertEqual(theirs is None, accepted, "regalia-kms offline_keys_record disagrees: %s" % theirs)
        return ours

    # ---- the pinned values ----

    def test_the_constants_are_the_kms_contract(self):
        self.assertEqual(ok.SCHEMA_RECORD, KMS_OFFLINE_KEYS_SCHEMA)
        self.assertEqual(ok.RECORD_DOMAIN, KMS_OFFLINE_KEYS_DOMAIN)
        self.assertEqual(ok.RETIRED_RECORD_DOMAIN, KMS_RETIRED_RECORD_DOMAIN)
        self.assertEqual(ok.GENESIS_RECORD_FIELDS, KMS_OFFLINE_KEYS_FIELDS)
        self.assertEqual(len(KMS_OFFLINE_KEYS_FIELDS), 14)
        if KMS is not None:
            self.assertEqual((KMS.OFFLINE_KEYS_SCHEMA, KMS.OFFLINE_KEYS_DOMAIN, KMS.OFFLINE_KEYS_FIELDS),
                             (KMS_OFFLINE_KEYS_SCHEMA, KMS_OFFLINE_KEYS_DOMAIN, KMS_OFFLINE_KEYS_FIELDS))

    def test_the_generated_record_has_the_contracts_shape(self):
        self.assertEqual(set(self.document), {"record", "signature"})
        record = self.document["record"]
        self.assertEqual(tuple(sorted(record)), tuple(sorted(KMS_OFFLINE_KEYS_FIELDS)))
        self.assertEqual((record["schema"], record["event"]), (KMS_OFFLINE_KEYS_SCHEMA, "generate"))
        self.assertEqual(record["root_entry"], {"alg": "ed25519", "key": self.root})
        self.assertEqual(record["root_fingerprint"], hashlib.sha256(bytes.fromhex(self.root)).hexdigest())
        published = record["publics"]["anchor-policy"]
        self.assertEqual((sorted(published), published["alg"]), (["alg", "spki"], "ecdsa-p256"))
        from cryptography.hazmat.primitives import serialization
        point = serialization.load_der_public_key(base64.b64decode(published["spki"])).public_bytes(
            serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint).hex()
        self.assertEqual(record["anchor_policy_entry"], {"alg": "ecdsa-p256", "key": point})
        self.assertEqual(record["operation_proof"]["anchor-policy"], "verified")
        self.assertEqual(ok.anchor_fingerprint(record["anchor_policy_entry"]), hashlib.sha256(bytes.fromhex(point)).hexdigest())

    def test_the_signature_is_over_the_kms_domain_and_no_other(self):
        from cryptography.exceptions import InvalidSignature
        from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey
        public = Ed25519PublicKey.from_public_bytes(bytes.fromhex(self.root))
        signature = bytes.fromhex(self.document["signature"])
        public.verify(signature, KMS_OFFLINE_KEYS_DOMAIN + ok.canonical(self.document["record"]))
        with self.assertRaises(InvalidSignature):
            public.verify(signature, KMS_RETIRED_RECORD_DOMAIN + ok.canonical(self.document["record"]))

    def test_the_generated_record_is_accepted(self):
        self.agree(self.document, True)

    # ---- the genesis step's three cases at the record level: pass (above), missing, forged ----

    def test_a_missing_record_is_refused_by_the_cli(self):
        err = io.StringIO()
        with unittest.mock.patch("sys.stderr", err):
            rc = ok.main(["genesis-check", "--record", os.path.join(self.gen, "absent.json"), "--sealed", self.sealed])
        self.assertEqual(rc, 1)
        self.assertIn("REFUSED", err.getvalue())

    def test_forged_records_are_refused(self):
        from cryptography.hazmat.primitives.asymmetric import ec
        from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
        from cryptography.hazmat.primitives import serialization
        other = Ed25519PrivateKey.generate()
        other_hex = other.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw).hex()
        swapped = ec.generate_private_key(ec.SECP256R1()).public_key()
        swapped_point = swapped.public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint).hex()
        swapped_spki = base64.b64encode(swapped.public_bytes(serialization.Encoding.DER,
                                                             serialization.PublicFormat.SubjectPublicKeyInfo)).decode()
        record = self.document["record"]

        def edited(**changes):
            r = copy.deepcopy(record)
            r.update(changes)
            return r
        another_k_a = edited(anchor_policy_entry={"alg": "ecdsa-p256", "key": swapped_point},
                             publics=dict(record["publics"], **{"anchor-policy": {"alg": "ecdsa-p256", "spki": swapped_spki}}))
        cases = {
            "another K_A, the root's signature kept": {"record": another_k_a, "signature": self.document["signature"]},
            "another K_A, signed by another key naming itself": self.signed(
                dict(another_k_a, root_entry={"alg": "ed25519", "key": other_hex},
                     root_fingerprint=hashlib.sha256(bytes.fromhex(other_hex)).hexdigest()), key=other),
            "another K_A, naming the root, signed by another key": self.signed(another_k_a, key=other),
            "the root's, under the retired domain": self.signed(record, domain=KMS_RETIRED_RECORD_DOMAIN),
            "the signature truncated": {"record": record, "signature": self.document["signature"][:126]},
            "the signature in capitals": {"record": record, "signature": self.document["signature"].upper()},
            "a third top-level field": dict(self.document, note="x"),
        }
        for name, document in cases.items():
            with self.subTest(case=name):
                self.agree(document, False)

    def test_each_content_rule_refuses_with_the_roots_own_signature(self):
        """Re-signed by the real root, so only the rule under test can refuse."""
        record = self.document["record"]
        other_point = record["anchor_policy_entry"]["key"][:-2] + ("00" if record["anchor_policy_entry"]["key"][-2:] != "00" else "01")
        cases = {
            "a field missing": {k: v for k, v in record.items() if k != "files"},
            "a field added": dict(record, note="x"),
            "event forms-verified": dict(record, event="forms-verified"),
            "threshold above shares": dict(record, threshold=record["shares"] + 1),
            "threshold a string": dict(record, threshold=str(record["threshold"])),
            "master_id a number": dict(record, master_id=7),
            "root_fingerprint another's": dict(record, root_fingerprint="00" * 32),
            "anchor_policy_entry not its published key": dict(record, anchor_policy_entry={"alg": "ecdsa-p256", "key": other_point}),
            "anchor_policy_entry an ed25519 key": dict(record, anchor_policy_entry={"alg": "ed25519", "key": self.root}),
            "no published anchor-policy key": dict(record, publics={k: v for k, v in record["publics"].items() if k != "anchor-policy"}),
            "no generation proof for K_A": dict(record, operation_proof={k: v for k, v in record["operation_proof"].items()
                                                                          if k != "anchor-policy"}),
            "K_A's proof not verified": dict(record, operation_proof=dict(record["operation_proof"], **{"anchor-policy": "skipped"})),
        }
        for name, mutated in cases.items():
            with self.subTest(case=name):
                self.agree(self.signed(mutated), False)

    def test_a_genuine_record_of_another_event_is_refused(self):
        """verify-forms' record: the same root, the same domain, event forms-verified. Only the event tells it apart."""
        with open(os.path.join(self.gen, ok.FILES[1])) as f:
            typed = "\n".join(line for line in f.read().splitlines() if line.strip()) + "\n"
        with unittest.mock.patch("sys.stdin", io.StringIO(typed)), unittest.mock.patch("sys.stdout", io.StringIO()):
            self.assertEqual(ok.main(["verify-forms", "--sealed", self.sealed, "--shares-file", os.path.join(self.gen, ok.FILES[1])]), 0)
        forms = [n for n in os.listdir(self.gen) if n.startswith("forms-verified-") and n.endswith(".record.json")]
        self.assertEqual(len(forms), 1)
        with open(os.path.join(self.gen, forms[0])) as f:
            document = json.load(f)
        self.assertEqual(document["record"]["event"], "forms-verified")
        self.agree(document, False)

    # ---- the typed second channel (#134; the owner's decision pending, the switch defaults ON) ----

    def test_the_typed_fingerprint_is_compared_with_the_records(self):
        record = ok.genesis_record(self.document, self.root)
        fingerprint = ok.anchor_fingerprint(record["anchor_policy_entry"])
        ok.typed_anchor_matches(record, fingerprint + "\n")
        ok.typed_anchor_matches(record, " " + fingerprint.upper() + " ")
        for typed in ("", fingerprint[:63], ("0" if fingerprint[0] != "0" else "1") + fingerprint[1:], record["root_fingerprint"]):
            with self.subTest(typed=typed[:8]):
                with self.assertRaises(ok.Refused):
                    ok.typed_anchor_matches(record, typed)

    def test_the_cli_prints_the_root_key_and_never_k_a(self):
        record = self.document["record"]
        fingerprint = ok.anchor_fingerprint(record["anchor_policy_entry"])
        out = io.StringIO()
        with unittest.mock.patch("sys.stdin", io.StringIO(fingerprint + "\n")), unittest.mock.patch("sys.stdout", out):
            rc = ok.main(["genesis-check", "--record", os.path.join(self.gen, "offline-keys.record.json"), "--sealed", self.sealed,
                          "--typed-anchor"])
        self.assertEqual(rc, 0)
        self.assertIn("ROOT-KEY %s\n" % self.root, out.getvalue())       # bare hex: what regalia-kms's --root-key takes for Ed25519
        if KMS is not None:
            self.assertEqual(KMS.root_key(self.root), self.root)
        self.assertNotIn(fingerprint, out.getvalue())
        self.assertNotIn(record["anchor_policy_entry"]["key"], out.getvalue())

    def test_generate_prints_the_fingerprint_the_sheet_takes(self):
        """Step o's output: ANCHOR-POLICY-FINGERPRINT, the SHA-256 kms's propose --genesis shows beside K_A."""
        import tempfile
        d = tempfile.mkdtemp(dir=self.d)
        out = io.StringIO()
        with unittest.mock.patch("sys.stdout", out):
            rc = ok.main(["generate", "--threshold", "2", "--shares", "3", "--out", d, "--breakglass-recipient",
                          os.path.join(self.d, "bg.recipient")]) if writer.HAVE_AGE else None
        if rc is None:
            deps.skip_dep(self, "age is not installed: generate's CLI needs it")
        self.assertEqual(rc, 0)
        with open(os.path.join(d, "offline-keys.record.json")) as f:
            entry = json.load(f)["record"]["anchor_policy_entry"]
        lines = [l for l in out.getvalue().splitlines() if l.startswith("ANCHOR-POLICY-FINGERPRINT ")]
        self.assertEqual(len(lines), 1)
        self.assertEqual(lines[0].split()[1], hashlib.sha256(bytes.fromhex(entry["key"])).hexdigest())


